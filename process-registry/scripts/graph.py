#!/usr/bin/env python3
"""Write GRAPH.md: a Mermaid map of every runbook's stages and dependencies.

  python graph.py <registry> [--stdout]

The graph is built from process.yaml (needs, gate, depends_on), so it can never
disagree with the definitions. Run it after every merge.
"""
import argparse
import re
import sys
from pathlib import Path

try:
    import yaml
except ImportError:
    sys.exit("graph needs PyYAML. Install it with: pip install pyyaml")


def node(*parts):
    return re.sub(r"[^A-Za-z0-9]", "_", "__".join(parts))


def build(registry):
    lines = ["flowchart TD"]
    edges, used = [], {}
    for rb in sorted(p for p in (registry / "runbooks").iterdir() if p.is_dir()):
        proc = rb / "process.yaml"
        if not proc.is_file():
            continue
        try:
            data = yaml.safe_load(proc.read_text()) or {}
        except yaml.YAMLError:
            continue
        rid = rb.name
        human = data.get("human_gate") if isinstance(data.get("human_gate"), list) else []
        label = f"{rid} ({data.get('status', '?')} v{data.get('version', '?')})"
        lines.append(f'  subgraph {node("rb", rid)}["{label}"]')
        for s in data.get("stages") or []:
            if not isinstance(s, dict) or "id" not in s:
                continue
            sid = str(s["id"])
            marks = []
            if s.get("gate"):
                marks.append("QA gate")
            if sid in human:
                marks.append("human yes")
            text = sid + (f"<br/>{' + '.join(marks)}" if marks else "")
            lines.append(f'    {node(rid, sid)}["{text}"]')
            for need in s.get("needs") or []:
                edges.append(f"  {node(rid, str(need))} --> {node(rid, sid)}")
        lines.append("  end")
        for dep in data.get("depends_on") or []:
            dep = str(dep)
            kind, _, name = dep.partition("/")
            target = node("rb", name) if kind == "runbooks" else node("skill", name)
            if kind == "skills":
                used[target] = dep
            edges.append(f"  {node('rb', rid)} -. uses .-> {target}")
    for target, dep in sorted(used.items()):
        lines.append(f'  {target}(["{dep}"])')
    return "\n".join(lines + edges)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("registry")
    ap.add_argument("--stdout", action="store_true", help="print instead of writing GRAPH.md")
    args = ap.parse_args()
    registry = Path(args.registry).resolve()
    if not (registry / "runbooks").is_dir():
        sys.exit(f"error: {registry} has no runbooks/ folder")
    doc = ("# Process graph\n\nGenerated by `tools/graph.py` from every `process.yaml`. Do not edit by hand.\n\n"
           "```mermaid\n" + build(registry) + "\n```\n")
    if args.stdout:
        print(doc)
    else:
        (registry / "GRAPH.md").write_text(doc)
        print(f"wrote {registry / 'GRAPH.md'}")


if __name__ == "__main__":
    main()
